/**
 * Emits `worker/migrations/004_auth.sql` from the live better-auth config.
 *
 *   node scripts/gen-auth-schema.mjs
 *
 * better-auth owns its table shape and changes it between versions; hand-typing
 * the DDL is how a column goes missing and every sign-in 500s in production.
 * This asks the library itself, through a Kysely dialect that compiles SQL
 * without ever connecting, so the output is the schema this exact version wants.
 */

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { getMigrations } from 'better-auth/db/migration';
import { DummyDriver, Kysely, SqliteAdapter, SqliteIntrospector, SqliteQueryCompiler } from 'kysely';

import { authOptions } from '../worker/auth/options.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(root, 'worker/migrations/004_auth.sql');

/** Compiles, never executes. The introspector reports no tables, so every
 *  table is emitted as a fresh CREATE. */
const db = new Kysely({
  dialect: {
    createAdapter: () => new SqliteAdapter(),
    createDriver: () => new DummyDriver(),
    createIntrospector: (instance) => new SqliteIntrospector(instance),
    createQueryCompiler: () => new SqliteQueryCompiler(),
  },
});

// Every provider switched on, so the generated schema is the full one no matter
// which secrets happen to be present on the machine running this.
const options = authOptions({
  BETTER_AUTH_SECRET: 'schema-generation-only',
  GOOGLE_CLIENT_ID: 'x',
  GOOGLE_CLIENT_SECRET: 'x',
  APPLE_CLIENT_ID: 'x',
  APPLE_CLIENT_SECRET: 'x',
  LINKEDIN_CLIENT_ID: 'x',
  LINKEDIN_CLIENT_SECRET: 'x',
});

const { compileMigrations } = await getMigrations({
  ...options,
  database: { db, type: 'sqlite' },
});

const sql = await compileMigrations();

const header = `-- Generated by scripts/gen-auth-schema.mjs — do not edit by hand.
--
-- better-auth's own tables (user, session, account, verification) plus the
-- fields our config adds: \`nickname\` for the leaderboard name and
-- \`isAnonymous\` from the anonymous plugin.
--
--   npx wrangler d1 execute quadro --remote --file worker/migrations/004_auth.sql

`;

writeFileSync(out, header + sql.trim() + '\n');
console.log(`wrote ${out}`);
